import type { Checklist, ItemDef, ItemRecord, ItemStatus, PanelValue } from "./checklists/types";
import { treadPercent } from "./checklists/types";

/**
 * Evidence engine: turns answers, photos, OBD reads and AI findings into a review of the inspection —
 * what still blocks sign-off, what disagrees with what, and the summary the report prints.
 * Pure and dependency-free, so the app and finalizeReport run exactly the same rules.
 */

export interface ReviewPhoto {
  id: string;
  sectionKey: string;
  itemKey: string;
  uploadState: "pending" | "uploaded";
}

/** Extra facts read during the ECU scan. Optional: older reads don't have them. */
export interface EcuExtended {
  vin: string | null;
  /** From the ECU (PID A6); few cars report it. */
  odometerKm: number | null;
  distanceSinceClearKm: number | null;
  warmUpsSinceClear: number | null;
  distanceWithMilKm: number | null;
  permanent: string[];
  /** Readiness monitors the car has; complete false = self-test not finished. */
  monitors: { name: string; complete: boolean }[];
  /** Signs codes were cleared recently, worded for the buyer. */
  flags: { id: string; title: string; body: string }[];
}

export interface ReviewObdRead {
  id: string;
  sectionKey: string;
  itemKey: string;
  payload: { stored: string[]; pending: string[]; milOn: boolean | null; simulated: boolean; extended?: EcuExtended | null };
  /** Epoch ms; reads without a time count as oldest. */
  capturedAtMs?: number;
}

export type FindingSeverity = "info" | "monitor" | "attention" | "urgent";

export interface ReviewFinding {
  id: string;
  sectionKey: string;
  itemKey: string;
  observedCondition: string;
  severity: FindingSeverity;
  verificationStatus: "ai_suggested" | "awaiting_verification" | "confirmed" | "dismissed";
}

export interface ReviewInput {
  checklist: Checklist;
  sections: Record<string, { items?: Record<string, ItemRecord> } | undefined>;
  photos: ReviewPhoto[];
  obdReads: ReviewObdRead[];
  findings: ReviewFinding[];
}

export type IssueKind =
  | "critical_unanswered"
  | "missing_reason"
  | "unverified_ai"
  | "contradiction"
  | "missing_photo"
  | "photo_uploading"
  | "unanswered"
  | "simulated_obd"
  | "obd_cleared"
  | "odometer_mismatch";

export interface Issue {
  kind: IssueKind;
  sectionKey: string;
  itemKey: string;
  /** Plain sentence for the inspector, naming the check. */
  message: string;
}

export interface FlaggedItem {
  sectionKey: string;
  sectionTitle: string;
  itemKey: string;
  label: string;
  status: "attention" | "defect";
  value: string | null;
  remarks: string | null;
  critical: boolean;
  photoIds: string[];
  obdReadId: string | null;
  /** Inspector-confirmed findings on this item. */
  findings: { id: string; observedCondition: string; severity: FindingSeverity }[];
}

export interface NotInspectedItem {
  sectionKey: string;
  sectionTitle: string;
  itemKey: string;
  label: string;
  reason: string | null;
}

export type Verdict = "no_major_issues" | "issues_found" | "serious_issues";

export interface InspectionSummaryReport {
  verdict: Verdict;
  counts: { defect: number; attention: number; notInspected: number; unanswered: number; answered: number; total: number };
  /** Every attention or defect item. Generated by rule, so nothing flagged can be dropped. */
  flagged: FlaggedItem[];
  notInspected: NotInspectedItem[];
  /** Latest ECU read, when there is one. */
  ecu: { stored: string[]; pending: string[]; milOn: boolean | null; simulated: boolean; extended?: EcuExtended | null } | null;
}

export interface Review {
  /** Must be empty before sign-off. */
  blockers: Issue[];
  /** Shown before sign-off and printed in the report, but don't block. */
  warnings: Issue[];
  summary: InspectionSummaryReport;
  ready: boolean;
}

const ECU_ITEM = "ecu_scan";
const LAMPS_ITEM = "warning_lamps";
const ODOMETER_ITEM = "odometer";

/** Display text for an answer, e.g. "Repainted · Good" for a panel or "2.4 mm (13%)" for tread. */
export function formatValue(def: ItemDef, record: ItemRecord): string | null {
  const v = record.value;
  if (v === undefined || v === null) return null;
  if (typeof v === "object") {
    const p = v as PanelValue;
    return [p.paint && `Paint: ${p.paint}`, p.structure && `Structure: ${p.structure}`].filter(Boolean).join(" · ") || null;
  }
  if (def.input.kind === "tread" && typeof v === "number") return `${v} mm (${treadPercent(v)}% left)`;
  if (typeof v === "number") return `${v.toLocaleString("en-IN")}${record.unit ? ` ${record.unit}` : ""}`;
  return v;
}

/** What the latest OBD read says the ECU-scan answer should be. */
function ecuLabel(read: ReviewObdRead["payload"]): string {
  return read.stored.length ? "Stored codes" : read.pending.length ? "Pending codes" : "No codes";
}

function latest<T extends { capturedAtMs?: number }>(list: T[]): T | undefined {
  return list.reduce<T | undefined>((a, b) => (!a || (b.capturedAtMs ?? 0) >= (a.capturedAtMs ?? 0) ? b : a), undefined);
}

export function reviewInspection(input: ReviewInput): Review {
  const blockers: Issue[] = [];
  const warnings: Issue[] = [];
  const flagged: FlaggedItem[] = [];
  const notInspected: NotInspectedItem[] = [];
  const counts = { defect: 0, attention: 0, notInspected: 0, unanswered: 0, answered: 0, total: 0 };

  const photosByItem = group(input.photos);
  const findingsByItem = group(input.findings);
  const readsByItem = group(input.obdReads);
  const latestEcu = latest(input.obdReads.filter((r) => r.itemKey === ECU_ITEM));

  let seriousDefect = false;

  for (const section of input.checklist.sections) {
    const items = input.sections[section.key]?.items ?? {};
    for (const def of section.items) {
      counts.total++;
      const key = `${section.key}/${def.key}`;
      const record = items[def.key];
      const status: ItemStatus | undefined = record?.status;
      const photos = photosByItem.get(key) ?? [];
      const findings = findingsByItem.get(key) ?? [];
      const at = (kind: IssueKind, message: string): Issue => ({ kind, sectionKey: section.key, itemKey: def.key, message });

      // AI suggestions must be confirmed or dismissed by a person before anything is signed.
      for (const f of findings) {
        if (f.verificationStatus === "ai_suggested" || f.verificationStatus === "awaiting_verification") {
          blockers.push(at("unverified_ai", `${def.label}: confirm or dismiss the AI suggestion "${f.observedCondition}".`));
        }
      }
      if (photos.some((p) => p.uploadState === "pending")) {
        blockers.push(at("photo_uploading", `${def.label}: a photo is still uploading. Go online to finish.`));
      }

      if (!status) {
        if (def.critical) blockers.push(at("critical_unanswered", `${def.label} is a critical check and isn't answered.`));
        else {
          counts.unanswered++;
          warnings.push(at("unanswered", `${def.label} isn't answered. It will show as "Not checked".`));
        }
        continue;
      }
      counts.answered++;

      if (status === "not_inspected") {
        counts.notInspected++;
        const reason = record?.notInspectedReason?.trim() || null;
        if (!reason) blockers.push(at("missing_reason", `${def.label} is marked not inspected without a reason.`));
        notInspected.push({ sectionKey: section.key, sectionTitle: section.title, itemKey: def.key, label: def.label, reason });
        continue;
      }
      if (status === "not_applicable") continue;

      // Contradictions: two pieces of evidence that can't both be right.
      const reads = readsByItem.get(key) ?? [];
      const ecuRead = def.key === ECU_ITEM ? latest(reads) : undefined;
      if (ecuRead && record?.value !== ecuLabel(ecuRead.payload)) {
        blockers.push(
          at(
            "contradiction",
            `${def.label} is answered "${String(record?.value)}" but the latest read from the car shows ${describeCodes(ecuRead.payload)}.`,
          ),
        );
      }
      if (def.key === LAMPS_ITEM && status === "good" && latestEcu?.payload.milOn) {
        blockers.push(at("contradiction", `${def.label} says none lit, but the car reported the check-engine light on.`));
      }
      const rated = status === "good" || status === "acceptable";
      for (const f of findings) {
        if (rated && f.verificationStatus === "confirmed" && (f.severity === "attention" || f.severity === "urgent")) {
          blockers.push(
            at("contradiction", `${def.label} is rated ${status} but a confirmed finding says "${f.observedCondition}".`),
          );
        }
      }
      if (ecuRead?.payload.simulated) {
        warnings.push(at("simulated_obd", `${def.label} is based on simulated data, not a real car. The report will say so.`));
      }
      const ext = def.key === ECU_ITEM ? ecuRead?.payload.extended : null;
      if (ext?.flags.length) {
        warnings.push(at("obd_cleared", `The ECU scan found: ${ext.flags.map((f) => f.title.toLowerCase()).join("; ")}. Ask the seller.`));
      }
      // Odometer rollback check: the dashboard reading against what the ECU reports.
      const ecuOdo = latestEcu?.payload.extended?.odometerKm;
      if (def.key === ODOMETER_ITEM && typeof record?.value === "number" && typeof ecuOdo === "number" && ecuOdo > 0) {
        const diff = Math.abs(record.value - ecuOdo);
        if (diff > Math.max(500, ecuOdo * 0.03)) {
          warnings.push(
            at(
              "odometer_mismatch",
              `${def.label} is ${record.value.toLocaleString("en-IN")} km but the engine computer reports ${Math.round(ecuOdo).toLocaleString("en-IN")} km. Check for a replaced cluster or tampering.`,
            ),
          );
        }
      }

      // Every flagged item needs to show its evidence.
      const isFlag = status === "attention" || status === "defect";
      if (def.photo && photos.length === 0) {
        if (isFlag) blockers.push(at("missing_photo", `${def.label} is rated ${status}; add a photo as evidence.`));
        else warnings.push(at("missing_photo", `${def.label} has no photo.`));
      }

      if (isFlag) {
        counts[status]++;
        if (status === "defect" && (def.critical || section.critical)) seriousDefect = true;
        flagged.push({
          sectionKey: section.key,
          sectionTitle: section.title,
          itemKey: def.key,
          label: def.label,
          status,
          value: record ? formatValue(def, record) : null,
          remarks: record?.remarks?.trim() || null,
          critical: !!def.critical,
          photoIds: photos.map((p) => p.id),
          obdReadId: latest(reads)?.id ?? null,
          findings: findings
            .filter((f) => f.verificationStatus === "confirmed")
            .map((f) => ({ id: f.id, observedCondition: f.observedCondition, severity: f.severity })),
        });
      }
    }
  }

  const urgentConfirmed = input.findings.some((f) => f.verificationStatus === "confirmed" && f.severity === "urgent");
  // Stored ECU codes rate the critical ECU-scan check as a defect, so they count as serious through it.
  const verdict: Verdict =
    seriousDefect || urgentConfirmed
      ? "serious_issues"
      : counts.defect + counts.attention > 0
        ? "issues_found"
        : "no_major_issues";

  return {
    blockers,
    warnings,
    ready: blockers.length === 0,
    summary: {
      verdict,
      counts,
      flagged,
      notInspected,
      ecu: latestEcu
        ? {
            stored: latestEcu.payload.stored,
            pending: latestEcu.payload.pending,
            milOn: latestEcu.payload.milOn,
            simulated: latestEcu.payload.simulated,
            extended: latestEcu.payload.extended ?? null,
          }
        : null,
    },
  };
}

function describeCodes(p: ReviewObdRead["payload"]): string {
  const parts = [p.stored.length && `stored ${p.stored.join(", ")}`, p.pending.length && `pending ${p.pending.join(", ")}`].filter(
    Boolean,
  );
  return parts.length ? parts.join("; ") : "no codes";
}

function group<T extends { sectionKey: string; itemKey: string }>(list: T[]): Map<string, T[]> {
  const map = new Map<string, T[]>();
  for (const x of list) {
    const key = `${x.sectionKey}/${x.itemKey}`;
    map.set(key, [...(map.get(key) ?? []), x]);
  }
  return map;
}
